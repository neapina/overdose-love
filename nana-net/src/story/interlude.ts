import { stage, type GameState } from '../state/store';

/** short prose for the school day, built from what happened the night before */
export function schoolDay(s: GameState): string[] {
  const st = stage(s);
  const prev = s.day - 1;
  const late = !!s.flags[`late_d${prev}`];
  const forced = !!s.flags.forced_sleep;
  const hwDone = !!s.flags[`hw_done_d${prev}`];
  const out: string[] = [];

  if (forced) out.push('проснулась за столом. шея не поворачивается. на щеке отпечаток клавиатуры.');
  else if (late) out.push('будильник. второй будильник. мама стучит. голова как не моя.');
  else out.push(st >= 2 ? 'проснулась сама. первая мысль — не про школу.' : 'проснулась сама. за окном серо. норм.');

  if (s.day === 2) out.push('маю на первом уроке разложила блинчики прямо на парте. учитель сделал вид, что не видит.');
  else if (s.day === 3) out.push('история, тест. ' + (hwDone ? 'руки помнили, голова не очень. сдала.' : 'половину — наугад. маю пинала под партой.'));
  else if (s.day === 4) out.push(hwDone ? 'эссе сдала. «good», и слово computer подчёркнуто. не знаю, что это значит.' : 'эссе не сдала. «забыла дома». посмотрели как на всех, кто «забыл дома».');
  else if (s.day === 5) out.push('на большой перемене маю что-то про фестиваль. я кивала. думала про вечер.');
  else if (s.day === 6) out.push('уроки шли мимо. считала часы до вечера, как раньше до каникул.');
  else if (s.day === 7) out.push('суббота. короткий день. всё как склеенное не по порядку.');

  if (st === 0) out.push('— ты чего такая довольная? — спросила маю.\n— ничего.');
  else if (st === 1) out.push(s.mayu >= 3 ? '— долго вчера сидела? — маю.\n— немного.\nне поверила. но улыбнулась.' : '— ты вчера до трёх онлайн была, — маю.\n— ты тоже.\n— я нет.');
  else if (st === 2) out.push(s.mayu >= 3 ? 'маю села рядом на обеде. молчала. потом: «ты же знаешь, мне можно всё рассказать». знаю.' : 'маю сидела через две парты. не подошла. или подошла, а я не заметила.');
  else out.push(s.mayu >= 2 ? 'маю положила на парту блинчик в салфетке. записка: «ешь. пожалуйста». съела половину.' : 'не помню, говорила ли я сегодня хоть с кем-то.');

  if (st >= 1 && s.flags.ren_known && !s.flags.ren_gone) out.push(st >= 2 ? 'по дороге домой проверяла телефон. у меня нет интернета в телефоне.' : 'по дороге домой: он сейчас спит, наверное. он же ночью не спит.');
  if (s.flags.ren_gone) out.push('по дороге домой — ничего. просто дорога.');

  out.push(st >= 2 ? 'дома. сумку на пол. комп.' : 'дома. сумку на стул. сначала уроки, потом всё остальное.');
  return out;
}
