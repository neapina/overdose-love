import { stage, type GameState } from '../state/store';

/** short prose for the school day, built from what happened the night before */
export function schoolDay(s: GameState): string[] {
  const st = stage(s);
  const prev = s.day - 1;
  const late = !!s.flags[`late_d${prev}`];
  const forced = !!s.flags.forced_sleep;
  const hwDone = !!s.flags[`hw_done_d${prev}`];
  const out: string[] = [];

  if (forced) out.push('Проснулась за столом. Шея не поворачивается. Монитор чёрный, на клавиатуре — след от щеки.');
  else if (late) out.push('Будильник. Второй будильник. Мама стучит. Голова как чужая.');
  else out.push(st >= 2 ? 'Проснулась сама. Первая мысль — не про школу.' : 'Проснулась сама. За окном серо и тихо. Нормально.');

  if (s.day === 2) out.push('В школе Маю выложила блинчики на парту прямо на первом уроке. Учитель сделал вид, что не заметил.');
  else if (s.day === 3) out.push('История. Тест. ' + (hwDone ? 'Руки помнили ответы. Голова — не очень.' : 'Половину отвечала наугад. Маю пинала под партой.'));
  else if (s.day === 4) out.push(hwDone ? 'Эссе сдала. Учительница написала «good» и подчеркнула слово «computer».' : 'Эссе не сдала. Сказала, что забыла дома. Учительница посмотрела так, как смотрят на всех, кто «забыл дома».');
  else if (s.day === 5) out.push('На большой перемене Маю рассказывала что-то про фестиваль. Я кивала. Я думала про ночь.');
  else if (s.day === 6) out.push('Уроки шли мимо. Я считала часы до вечера — так, как раньше считала до каникул.');
  else if (s.day === 7) out.push('Последний день недели. Всё как в кино, где кадры склеены не по порядку.');

  if (st === 0) out.push('— Ты чего такая довольная? — спросила Маю.\n— Ничего.');
  else if (st === 1) out.push(s.mayu >= 3 ? '— Ты вчера долго сидела? — спросила Маю.\n— Немного.\nОна не поверила. Но улыбнулась.' : '— Ты вчера была в сети до трёх, — сказала Маю.\n— Ты тоже.\n— Я — нет.');
  else if (st === 2) out.push(s.mayu >= 3 ? 'Маю села рядом на обеде. Молчала. Потом сказала: «Ты можешь мне всё рассказать. Знаешь же». Знаю.' : 'Маю сидела через две парты. Не подошла. Или подошла — я не заметила.');
  else out.push(s.mayu >= 2 ? 'Маю положила мне на парту блинчик в салфетке. Записка: «ешь. пожалуйста». Я съела половину.' : 'Не помню, разговаривала ли я сегодня с кем-нибудь.');

  if (st >= 1 && s.flags.ren_known && !s.flags.ren_gone) out.push(st >= 2 ? 'По дороге домой ловила себя на том, что проверяю телефон. У меня нет интернета в телефоне.' : 'По дороге домой думала: он спит сейчас, наверное. Он же ночью не спит.');
  if (s.flags.ren_gone) out.push('По дороге домой — ничего. Просто дорога.');

  out.push(st >= 2 ? 'Дома. Сумку — на пол. Компьютер — сразу.' : 'Дома. Сумку — на стул. Сначала уроки. Потом всё остальное.');
  return out;
}
